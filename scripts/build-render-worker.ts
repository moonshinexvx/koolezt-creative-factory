import { execFileSync } from "node:child_process";
import { copyFile, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { existsSync } from "node:fs";
import { build } from "esbuild";
import ffmpegStatic from "ffmpeg-static";
import ffprobeStatic from "ffprobe-static";

if (process.platform !== "win32") throw new Error("The standalone render worker must be built on Windows.");
const output = resolve("dist/render-worker");
const archive = resolve("dist/CreativeFactoryRenderWorker-1.2.4-windows-x64.zip");
await rm(output, { recursive: true, force: true });
await rm(archive, { force: true });
await mkdir(output, { recursive: true });
const bundle = join(output, "worker.cjs");
await build({ entryPoints: [resolve("apps/render-worker/src/index.ts")], outfile: bundle, bundle: true, platform: "node", format: "cjs", target: "node22", minify: true, sourcemap: false, external: ["ffmpeg-static", "ffprobe-static"] });
const blob = join(output, "worker.blob");
const seaConfig = join(output, "sea-config.json");
await writeFile(seaConfig, JSON.stringify({ main: bundle, output: blob, disableExperimentalSEAWarning: true, useSnapshot: false, useCodeCache: false }));
execFileSync(process.execPath, ["--experimental-sea-config", seaConfig], { stdio: "inherit" });
const executable = join(output, "CreativeFactoryRenderWorker.exe");
await copyFile(process.execPath, executable);
const portableExecutable = Buffer.from(await readFile(executable));
const peHeader = portableExecutable.readUInt32LE(0x3c);
if (portableExecutable.toString("ascii", peHeader, peHeader + 4) !== "PE\0\0") throw new Error("Node executable has an invalid PE header.");
const optionalHeader = peHeader + 24;
const dataDirectories = portableExecutable.readUInt16LE(optionalHeader) === 0x20b ? optionalHeader + 112 : optionalHeader + 96;
const certificateEntry = dataDirectories + 4 * 8;
const certificateOffset = portableExecutable.readUInt32LE(certificateEntry);
const certificateSize = portableExecutable.readUInt32LE(certificateEntry + 4);
portableExecutable.writeUInt32LE(0, certificateEntry); portableExecutable.writeUInt32LE(0, certificateEntry + 4);
const unsignedExecutable = certificateOffset > 0 && certificateOffset + certificateSize === portableExecutable.length ? portableExecutable.subarray(0, certificateOffset) : portableExecutable;
await writeFile(executable, unsignedExecutable);
execFileSync(process.execPath, [resolve("node_modules/postject/dist/cli.js"), executable, "NODE_SEA_BLOB", blob, "--sentinel-fuse", "NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2"], { stdio: "inherit" });
if (!ffmpegStatic) throw new Error("ffmpeg-static did not provide a Windows binary.");
await copyFile(ffmpegStatic, join(output, "ffmpeg.exe"));
await copyFile(ffprobeStatic.path, join(output, "ffprobe.exe"));
await writeFile(join(output, "README.txt"), ["Koolezt Creative Factory Render Worker v1.2.4", "", "Use KooleztCreativeFactoryRenderWorker-Setup.exe for normal installation.", "The installer enrolls this computer using a one-time Setup Code and stores the worker credential with Windows DPAPI CurrentUser.", "Node.js and separate FFmpeg installation are not required."].join("\r\n"));
await writeFile(join(output, "launch-worker.vbs"), ["Set shell = CreateObject(\"WScript.Shell\")", "Set fileSystem = CreateObject(\"Scripting.FileSystemObject\")", "workerPath = fileSystem.GetParentFolderName(WScript.ScriptFullName) & \"\\\\CreativeFactoryRenderWorker.exe\"", "Do", "  exitCode = shell.Run(Chr(34) & workerPath & Chr(34), 0, True)", "  If exitCode = 0 Then WScript.Quit 0", "  WScript.Sleep 5000", "Loop"].join("\r\n"));
await rm(bundle, { force: true });
await rm(blob, { force: true });
await rm(seaConfig, { force: true });
execFileSync("tar.exe", ["-a", "-c", "-f", archive, "-C", output, "."], { stdio: "inherit" });
console.log(`Built ${executable}`);
console.log(`Packaged ${archive}`);
const candidates = [process.env.ISCC_PATH, "C:\\Program Files (x86)\\Inno Setup 6\\ISCC.exe", "C:\\Program Files\\Inno Setup 6\\ISCC.exe", join(process.env.LOCALAPPDATA ?? "", "Programs", "Inno Setup 6", "ISCC.exe")].filter((value): value is string => Boolean(value));
const iscc = candidates.find((value) => existsSync(value));
if (!iscc) throw new Error("Inno Setup 6 compiler was not found. Install the free Inno Setup compiler or set ISCC_PATH.");
execFileSync(iscc, [resolve("installer/render-worker.iss")], { stdio: "inherit" });
console.log(`Packaged ${resolve("dist/KooleztCreativeFactoryRenderWorker-1.2.4-Setup.exe")}`);
